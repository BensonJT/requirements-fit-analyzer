"""The generated markdown view of the tracker (design section 6).

`render()` writes `Application_Tracker.md` (only when CUTOVER is True) or
`Application_Tracker_PREVIEW.md` in the Job_Search directory. A hand-edit guard compares the
file's sha256 with the last `tracker.render_log` entry for that path and refuses to overwrite a
changed file unless forced. Output is deterministic for a given database, `today` and `now`.
"""
import difflib
import hashlib
import os
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from urllib.parse import quote

CUTOVER = False          # flipped by the user at cutover; while False the live file is never written
LIVE_NAME = "Application_Tracker.md"
PREVIEW_NAME = "Application_Tracker_PREVIEW.md"
ACTIVE_COLS = ["ID", "Applied", "Company", "Role", "Req", "Status", "Since", "Next action",
               "Follow-up", "Contact", "Folder"]
CLOSED_NAME = "Application_Tracker_Closed.md"
CLOSED_COLS = ["ID", "Applied", "Company", "Role", "Req", "Status", "Since", "Reason", "Folder"]
NETWORK_COLS = ["Platform", "Accepted", "Status", "Profile", "Notes"]


def job_dir_from_env(vault_dir=None):
    """The Job_Search directory from `vault_dir` or $JOBSEARCH_VAULT_DIR (None when neither is set)."""
    vault_dir = vault_dir or os.environ.get("JOBSEARCH_VAULT_DIR")
    if not vault_dir:
        return None
    from backend.finder.tracker_sync import job_search_dir
    return Path(job_search_dir(vault_dir))


@dataclass
class RenderResult:
    path: Path
    status: str                      # 'written' or 'refused'
    diff: str = ""
    sha256: str = ""
    preview: bool = False
    notes: list = field(default_factory=list)


def _cell(v):
    if v is None:
        return ""
    if isinstance(v, (date, datetime)):
        v = v.isoformat()[:10]
    return " ".join(str(v).split()).replace("|", "\\|")


def _folder_cell(folder):
    if not folder:
        return ""
    return f"[open]({quote(str(folder).strip('/'), safe='/')}/index.md)"


def _table(cols, rows):
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _active_row(r):
    return [str(r["app_id"]), _cell(r["date_applied"]), _cell(r["company"]), _cell(r["role"]),
            _cell(r["employer_job_id"]), _cell(r["status"]), _cell(r["status_date"]),
            _cell(r["next_action"]), _cell(r["follow_up_due"]), _cell(r["contacts"]),
            _folder_cell(r["folder"])]


def render_text(conn, *, preview=False, today=None, now=None):
    today = today or date.today()
    now = now or datetime.now(timezone.utc)
    rows = conn.execute("SELECT * FROM tracker.vw_applications "
                        "ORDER BY sort_order, status_date DESC, app_id DESC").fetchall()
    active = [r for r in rows if r["is_active"]]
    order = [r["status"] for r in conn.execute("SELECT status FROM tracker.status ORDER BY sort_order")]
    counts = {s: sum(1 for r in active if r["status"] == s) for s in order}
    closed_counts = {s: sum(1 for r in rows if not r["is_active"] and r["status"] == s) for s in order}
    horizon = today + timedelta(days=7)
    due = [r for r in active if r["follow_up_due"] and today <= r["follow_up_due"] <= horizon]
    overdue = [r for r in active if r["follow_up_due"] and r["follow_up_due"] < today]
    summary = ", ".join(f"{n} {s}" for s, n in counts.items() if n) or "no open applications"
    summary += f". Follow-ups due within 7 days: {len(due)}"
    if overdue:
        summary += f" (+{len(overdue)} overdue)"
    summary += "."
    networks = conn.execute("SELECT * FROM tracker.network ORDER BY platform").fetchall()

    node = "PRO:job-application-tracker-preview" if preview else "PRO:job-application-tracker"
    L = ["---", f"node_id: {node}", "node_type: area", "tags: [#professional #job-search #tracker]",
         "ai_edit_policy: read-only", f"rendered: {now.strftime('%Y-%m-%dT%H:%M:%SZ')}", "---",
         "# Application Tracker" + (" (preview)" if preview else ""), "",
         "> AI_USAGE: generated by `trk render` from PostgreSQL `resume.tracker`. "
         "Edit with `trk` (see `trk --help`), never by hand; hand edits are refused on the next render.",
         "", summary, "", f"## Active ({len(active)})", ""]
    L += _table(ACTIVE_COLS, [_active_row(r) for r in active])
    # Closed rows stay in the database only (user ruling 2026-10-20): the view is for open items.
    n_closed = sum(closed_counts.values())
    detail = ", ".join(f"{n} {s}" for s, n in closed_counts.items() if n)
    L += ["", f"Closed: {n_closed}" + (f" ({detail})" if detail else "")
          + ". They live in the database only; list them with `trk ls --closed`."]
    L += ["", f"## Consultant networks ({len(networks)})", ""]
    L += _table(NETWORK_COLS, [[_cell(n["platform"]), _cell(n["date_accepted"]), _cell(n["status"]),
                                _cell(n["profile_url"]), _cell(n["notes"])] for n in networks])
    return "\n".join(L) + "\n"


def render_closed_text(conn, *, status=None, since=None, now=None):
    """The on-demand closed-applications snapshot: every closed row (optionally one status and/or
    status date >= `since`), newest status date first, with a count per closed status."""
    now = now or datetime.now(timezone.utc)
    since = date.fromisoformat(since) if isinstance(since, str) else since
    rows = conn.execute("SELECT * FROM tracker.vw_applications WHERE NOT is_active "
                        "ORDER BY status_date DESC, app_id DESC").fetchall()
    order = [r["status"] for r in conn.execute("SELECT status FROM tracker.status ORDER BY sort_order")]
    if status and status not in order:
        from backend.tracker.store import TrackerError
        raise TrackerError(f"unknown status {status!r}; allowed: {', '.join(order)}")
    rows = [r for r in rows if (not status or r["status"] == status) and (not since or r["status_date"] >= since)]
    counts = {s: sum(1 for r in rows if r["status"] == s) for s in order}
    detail = ", ".join(f"{n} {s}" for s, n in counts.items() if n)
    summary = f"Closed: {len(rows)}" + (f" ({detail})" if detail else "")
    if status or since:
        summary += " [filter:" + (f" status {status}" if status else "") + (f" since {since}" if since else "") + "]"
    L = ["---", "node_id: PRO:job-application-tracker-closed", "node_type: area",
         "tags: [#professional #job-search #tracker]", "ai_edit_policy: read-only",
         f"rendered: {now.strftime('%Y-%m-%dT%H:%M:%SZ')}", "---", "# Application Tracker: Closed", "",
         "> AI_USAGE: on-demand snapshot from `trk closed-report`; not kept current; the database is the record.",
         "", summary + ".", ""]
    L += _table(CLOSED_COLS, [[str(r["app_id"]), _cell(r["date_applied"]), _cell(r["company"]), _cell(r["role"]),
                               _cell(r["employer_job_id"]), _cell(r["status"]), _cell(r["status_date"]),
                               _cell(r["close_reason"]), _folder_cell(r["folder"])] for r in rows])
    return "\n".join(L) + "\n"


def write_closed_report(conn, job_dir, *, status=None, since=None, now=None):
    """Write `Application_Tracker_Closed.md` (always overwritten, via tmp + replace). Returns (path, row count)."""
    text = render_closed_text(conn, status=status, since=since, now=now)
    path = Path(job_dir) / CLOSED_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(text.encode("utf-8"))
    os.replace(tmp, path)
    return path, text.count("\n| ") - 1


def target_path(job_dir, preview=False):
    """The live file only when CUTOVER is True and preview was not asked for; else the preview file."""
    live = CUTOVER and not preview
    return Path(job_dir) / (LIVE_NAME if live else PREVIEW_NAME), not live


def _sha(data):
    return hashlib.sha256(data).hexdigest()


def render(conn, job_dir=None, *, vault_dir=None, preview=False, force=False, today=None, now=None):
    """Write the view. Returns a RenderResult; status 'refused' (with a unified diff) when the
    target exists and does not match the last file we wrote, unless `force`."""
    job_dir = Path(job_dir) if job_dir else job_dir_from_env(vault_dir)
    if job_dir is None:
        from backend.tracker.store import TrackerError
        raise TrackerError("Job_Search directory unknown: set JOBSEARCH_VAULT_DIR")
    path, is_preview = target_path(job_dir, preview)
    text = render_text(conn, preview=is_preview, today=today, now=now)
    data = text.encode("utf-8")
    if path.exists() and not force:
        current = path.read_bytes()
        last = conn.execute("SELECT sha256 FROM tracker.render_log WHERE path = %s "
                            "ORDER BY rendered_at DESC LIMIT 1", [str(path)]).fetchone()
        if last is None or last["sha256"] != _sha(current):
            diff = "".join(difflib.unified_diff(
                current.decode("utf-8", "replace").splitlines(True), text.splitlines(True),
                fromfile=f"{path.name} (on disk)", tofile=f"{path.name} (would write)"))
            why = "no render_log entry for this file" if last is None else "file changed since last render"
            return RenderResult(path, "refused", diff, preview=is_preview, notes=[why])
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    digest = _sha(data)
    conn.execute("INSERT INTO tracker.render_log (path, sha256) VALUES (%s, %s)", [str(path), digest])
    return RenderResult(path, "written", sha256=digest, preview=is_preview)
